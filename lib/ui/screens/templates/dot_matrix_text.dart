class _DotMatrixPainter extends CustomPainter {
  final String text;
  final Color color;
  final double dotSize;
  final double spacing;
  final Map<String, List<int>> glyphs;

  _DotMatrixPainter({
    required this.text,
    required this.color,
    required this.dotSize,
    required this.spacing,
    required this.glyphs,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.fill;

    double xOffset = 0.0;
    final charSpacing = spacing * 1.6;

    for (int i = 0; i < text.length; i++) {
      final char = text[i];
      final rows = glyphs[char] ?? glyphs[' '];

      if (rows != null) {
        for (int row = 0; row < 7; row++) {
          final bitmask = rows[row];
          for (int col = 0; col < 5; col++) {
            if ((bitmask & (1 << (4 - col))) != 0) {
              final cx = xOffset + col * spacing + dotSize / 2;
              final cy = row * spacing + dotSize / 2;
              canvas.drawCircle(Offset(cx, cy), dotSize / 2, paint);
            }
          }
        }
      }
      xOffset += 5 * spacing + charSpacing;
    }
  }

  @override
  bool shouldRepaint(covariant _DotMatrixPainter old) {
    return old.text != text || old.color != color || old.dotSize != dotSize;
  }
}
